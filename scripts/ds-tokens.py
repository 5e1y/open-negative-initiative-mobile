#!/usr/bin/env python3
"""Writes android/.../ds/Tokens.kt from the desktop's design tokens, crates/oni-ui/ui/ds/tokens.slint
(itself generated from the Swift app's DSTokens.swift). ONI_RS names the Rust repository, else a sibling.

  scripts/ds-tokens.py           write the Kotlin copy
  scripts/ds-tokens.py --check   fail when the committed copy differs from what the tokens give
"""

import hashlib
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = "crates/oni-ui/ui/ds/tokens.slint"
OUT = os.path.join(HERE, "android/app/src/main/java/fr/courtillon/onimobile/ds/Tokens.kt")
DECL = re.compile(r"^\s*out property <(\w+)> ([a-z0-9-]+): (.+);\s*$")
KEYWORDS = {"as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface",
            "is", "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias",
            "typeof", "val", "var", "when", "while"}


def camel(words):
    head, *rest = words
    name = head + "".join(w[:1].upper() + w[1:] for w in rest)
    return f"`{name}`" if name in KEYWORDS else name


def number(text):
    value = float(text)
    return str(int(value)) if value == int(value) else text


def literal(kind, value):
    """The Kotlin declaration's keyword and value for one token, or None for a type it has no use for."""
    if kind == "length":
        return "val", number(value.removesuffix("px")) + ".dp"
    if kind == "float":
        return "const val", number(value) + "f"
    if kind == "int":
        return "const val", value
    if kind == "duration":
        return "const val", number(value.removesuffix("ms")) + "f"
    if kind == "string":
        return "const val", value
    if kind == "color":
        hex_ = value.removeprefix("#")
        if len(hex_) != 8:
            raise ValueError(f"colour {value}")
        return "val", f"Color(0x{hex_[6:8]}{hex_[0:6]})".upper().replace("COLOR(0X", "Color(0x")
    raise ValueError(f"type {kind}")


def generate(source):
    groups = {}
    for line in source.splitlines():
        match = DECL.match(line)
        if not match:
            continue
        kind, name, value = match.groups()
        group, *words = name.split("-")
        keyword, text = literal(kind, value)
        field = camel(words) + ("Ms" if kind == "duration" else "")
        groups.setdefault(group, []).append(f"        {keyword} {field} = {text}")
    if not groups:
        raise ValueError("no token in the source")
    digest = hashlib.sha256(source.encode()).hexdigest()
    out = [
        f"// Generated by scripts/ds-tokens.py from the desktop's {SOURCE}: never edit.",
        f"// Source sha256: {digest}",
        "@file:Suppress(\"unused\")",
        "",
        "package fr.courtillon.onimobile.ds",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.unit.dp",
        "",
        "/** The desktop's design tokens, grouped by their name's first word; durations in milliseconds. */",
        "object Tokens {",
    ]
    for group, lines in groups.items():
        out.append(f"    object {group[:1].upper() + group[1:]} {{")
        out.extend(lines)
        out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    rs = os.environ.get("ONI_RS") or os.path.join(HERE, "..", "open-negative-initiative-rs")
    with open(os.path.join(rs, SOURCE), encoding="utf-8") as f:
        kotlin = generate(f.read())
    if "--check" in sys.argv[1:]:
        try:
            with open(OUT, encoding="utf-8") as f:
                committed = f.read()
        except FileNotFoundError:
            committed = ""
        if committed != kotlin:
            sys.exit(f"{OUT} drifted from {SOURCE}: run scripts/ds-tokens.py")
        print("Tokens.kt matches the desktop's tokens")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(kotlin)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
